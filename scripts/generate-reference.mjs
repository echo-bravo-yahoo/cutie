// Generates docs/reference from the module schemas, so the documented options
// and the accepted options cannot drift apart. Run with:
//
//   npm run reference
//
// test/unit/reference.ts regenerates and diffs, so a schema change without a
// regeneration fails the suite.
import { mkdir, readdir, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { listModules, loadSchema } from "../src/util/modules.js";
import { UNIVERSAL_OPTION_SCHEMAS } from "../src/util/schema.js";
import { KINDS } from "../src/util/type-helpers.js";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

export const REFERENCE_DIR = join(REPO_ROOT, "docs", "reference");

const KIND_BLURBS = {
  trigger: "A trigger decides when a task runs and what message it starts.",
  read: "A read replaces the message with a value from somewhere else.",
  transform: "A transform changes the message on its way through a task.",
  control:
    "A control decides what the chain does next, rather than changing the message on its way through it.",
  output: "An output sends the message somewhere and passes it on unchanged.",
  connection:
    "A connection is a shared link to something outside the node, named by the steps that use it.",
};

function cell(value) {
  return value === undefined || value === "" ? "" : String(value);
}

function renderDefault(option) {
  if (option.required) return "";
  if (option.default === undefined) return "";

  return `\`${JSON.stringify(option.default)}\``;
}

function renderType(option) {
  if (!option.enum) return option.type;

  return option.enum.map((value) => `\`${value}\``).join(" or ");
}

function renderRange(option) {
  const bounds = [];

  if (option.min !== undefined && option.max !== undefined)
    bounds.push(`between ${option.min} and ${option.max}`);
  else if (option.min !== undefined) bounds.push(`at least ${option.min}`);
  else if (option.max !== undefined) bounds.push(`at most ${option.max}`);

  if (option.integer) bounds.push("a whole number");

  return bounds.length ? ` Must be ${bounds.join(", ")}.` : "";
}

function renderDescription(option) {
  const notes = [];

  // Skipped when the description already says so, which several of them do.
  if (option.interpolated && !option.description.includes("nterpolat"))
    notes.push("Supports ${...} interpolation.");

  return [option.description + renderRange(option), ...notes].join(" ").trim();
}

function table(rows) {
  const header = [
    "| Option | Type | Required | Default | Unit | Description |",
    "| --- | --- | --- | --- | --- | --- |",
  ];
  const body = rows.map((row) => `| ${row.map(cell).join(" | ")} |`);

  return [...header, ...body].join("\n");
}

function rowsFor(options) {
  return Object.entries(options).map(([name, option]) => [
    `\`${name}\``,
    renderType(option),
    option.required ? "**yes**" : "no",
    renderDefault(option),
    option.unit ? `\`${option.unit}\`` : "",
    renderDescription(option),
  ]);
}

// Every step accepts these, whatever its type, so they come from the same
// declaration the validator checks against rather than a table repeated here.
const UNIVERSAL_ROWS = rowsFor(UNIVERSAL_OPTION_SCHEMAS);

function renderModule(schema) {
  const rows = rowsFor(schema.options);

  return [
    `## \`${schema.type}\``,
    "",
    schema.description,
    "",
    rows.length
      ? table([...rows, ...UNIVERSAL_ROWS])
      : `Takes no options of its own.\n\n${table(UNIVERSAL_ROWS)}`,
    "",
  ].join("\n");
}

async function renderKind(kind, subKinds) {
  const schemas = [];

  for (const subKind of subKinds) {
    const type = `${kind}:${subKind}`;
    // loadSchema rejects when a module declares none, which is what keeps this
    // page from silently omitting a module.
    schemas.push(await loadSchema(type));
  }

  return [
    `# ${kind} reference`,
    "",
    KIND_BLURBS[kind],
    "",
    "<!-- Generated by scripts/generate-reference.mjs. Edit the module's schema, not this file. -->",
    "",
    ...schemas.map(renderModule),
    "",
  ].join("\n");
}

function renderIndex(modules) {
  const sections = KINDS.map((kind) => [
    `## ${kind}s`,
    "",
    ...modules[kind].map(
      (subKind) =>
        `- [\`${kind}:${subKind}\`](./${kind}s.md#${kind}${subKind})`,
    ),
    "",
  ]).flat();

  return [
    "# Configuration reference",
    "",
    "Every option every module accepts, generated from the schemas the runtime validates against.",
    "",
    "<!-- Generated by scripts/generate-reference.mjs. Edit the module's schema, not this file. -->",
    "",
    ...sections,
  ].join("\n");
}

// Returns filename -> contents, so a test can diff without writing anything.
export async function generateReference() {
  const modules = await listModules();
  const pages = { "README.md": renderIndex(modules) };

  for (const kind of KINDS)
    pages[`${kind}s.md`] = await renderKind(kind, modules[kind]);

  return pages;
}

export async function writeReference(directory = REFERENCE_DIR) {
  const pages = await generateReference();

  await mkdir(directory, { recursive: true });

  // Removes a page for a kind that no longer exists, so the directory always
  // matches what the generator produces.
  for (const existing of await readdir(directory))
    if (!pages[existing]) await rm(join(directory, existing));

  for (const [name, contents] of Object.entries(pages))
    await writeFile(join(directory, name), contents);

  return Object.keys(pages);
}

// Only writing when invoked directly, so a test can import the generator.
if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const written = await writeReference();
  console.log(`Wrote ${written.length} reference pages to docs/reference.`);
}
